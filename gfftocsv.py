def download_file(url, output_file):
    """
    Download a file from a URL and save it locally
    """
    import requests

    print(f"Downloading {url}...")
    response = requests.get(url, stream=True)
    response.raise_for_status()

    with open(output_file, 'wb') as f:
        for chunk in response.iter_content(chunk_size=8192):
            f.write(chunk)

    print(f"Downloaded to {output_file}")

def gff_to_csv(gff_file, csv_file):
    """
    Convert a GFF file to CSV format
    """
    # Determine if the file is gzipped
    is_gzipped = gff_file.endswith('.gz')
    opener = gzip.open if is_gzipped else open

    print(f"Converting {gff_file} to {csv_file}...")

    # Define CSV header fields
    fieldnames = [
        'seqid', 'source', 'type', 'start', 'end', 'score',
        'strand', 'phase', 'attributes', 'gene_name', 'product'
    ]

    with opener(gff_file, 'rt') as gff, open(csv_file, 'w', newline='') as csvfile:
        # Create CSV writer
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()

        # Process GFF file
        for line in gff:
            # Skip comment lines
            if line.startswith('#'):
                continue

            # Split the line by tabs
            fields = line.strip().split('\t')

            # Skip lines that don't have the expected number of fields
            if len(fields) != 9:
                continue

            # Parse the attributes field into a dictionary
            attributes_dict = {}
            if fields[8] != '.':
                attributes = fields[8].split(';')
                for attr in attributes:
                    if '=' in attr:
                        key, value = attr.split('=', 1)
                        attributes_dict[key] = value

            # Extract gene name and product if available
            gene_name = attributes_dict.get('Name', attributes_dict.get('gene', ''))
            product = ''

            # Look for product in attributes
            if 'product' in attributes_dict:
                product = attributes_dict['product']

            # Create row data
            row = {
                'seqid': fields[0],
                'source': fields[1],
                'type': fields[2],
                'start': fields[3],
                'end': fields[4],
                'score': fields[5],
                'strand': fields[6],
                'phase': fields[7],
                'attributes': fields[8],
                'gene_name': gene_name,
                'product': product
            }

            # Write the row to the CSV file
            writer.writerow(row)

    print(f"Conversion complete. CSV file saved as {csv_file}")

