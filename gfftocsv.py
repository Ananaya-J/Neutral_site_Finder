import csv
import sys

def gff_to_csv(gff_file, csv_file):
    """
    Convert a GFF file to CSV format

    Parameters:
    gff_file (str): Path to input GFF file
    csv_file (str): Path to output CSV file
    """

    # Define headers for CSV file based on GFF format
    csv_headers = ['seqid', 'source', 'type', 'start', 'end', 'score', 'strand', 'phase', 'attributes']

    # Open files
    with open(gff_file, 'r') as infile, open(csv_file, 'w', newline='') as outfile:
        # Create CSV writer
        csv_writer = csv.writer(outfile)

        # Write header
        csv_writer.writerow(csv_headers)

        # Process each line
        for line in infile:
            # Skip comments and empty lines
            if line.startswith('#') or not line.strip():
                continue

            # Split GFF fields
            fields = line.strip().split('\t')

            # Write to CSV
            csv_writer.writerow(fields)

    print(f"Conversion complete. CSV file saved to {csv_file}")

def gff_to_csv_with_attribute_parsing(gff_file, csv_file):
    """
    Convert a GFF file to CSV format with expanded attributes

    Parameters:
    gff_file (str): Path to input GFF file
    csv_file (str): Path to output CSV file
    """

    # Define basic headers
    basic_headers = ['seqid', 'source', 'type', 'start', 'end', 'score', 'strand', 'phase']

    # Set to track all attribute keys found in the file
    all_attr_keys = set()

    # First pass: identify all attribute keys
    with open(gff_file, 'r') as infile:
        for line in infile:
            if line.startswith('#') or not line.strip():
                continue

            fields = line.strip().split('\t')
            if len(fields) >= 9:
                # Parse attributes
                attr_str = fields[8]
                attr_pairs = attr_str.split(';')

                for pair in attr_pairs:
                    if '=' in pair:
                        key, _ = pair.split('=', 1)
                        all_attr_keys.add(key)

    # Convert to sorted list for consistent column order
    attr_keys = sorted(list(all_attr_keys))

    # Full headers including attributes
    csv_headers = basic_headers + attr_keys

    # Second pass: write the CSV with parsed attributes
    with open(gff_file, 'r') as infile, open(csv_file, 'w', newline='') as outfile:
        csv_writer = csv.writer(outfile)
        csv_writer.writerow(csv_headers)

        for line in infile:
            if line.startswith('#') or not line.strip():
                continue

            fields = line.strip().split('\t')
            if len(fields) < 9:
                continue  # Skip lines with insufficient fields

            # Get basic fields
            basic_values = fields[:8]

            # Parse attributes into a dictionary
            attr_dict = {}
            attr_str = fields[8]
            attr_pairs = attr_str.split(';')

            for pair in attr_pairs:
                if '=' in pair:
                    key, value = pair.split('=', 1)
                    attr_dict[key] = value

            # Create a row with basic fields and attributes
            row = basic_values + [attr_dict.get(key, '') for key in attr_keys]
            csv_writer.writerow(row)

    print(f"Conversion complete with parsed attributes. CSV file saved to {csv_file}")

